def test_checkpoint_comparison_schema_and_deltas():
    """Verify ExperimentComparator.compare schema, delta calculation, and preferred direction."""
    exp_a = {
        "id": "model_baseline",
        "name": "Model Baseline",
        "metrics": {
            "summary": {
                "accuracy": 0.850,
                "ece": 0.080,
                "duration_seconds": 12.0,
            }
        },
    }
    exp_b = {
        "id": "model_candidate",
        "name": "Model Candidate",
        "metrics": {
            "summary": {
                "accuracy": 0.900,  # Improved (+0.05)
                "ece": 0.030,       # Improved (-0.05)
                "duration_seconds": 15.0, # Regressed (+3.0)
            }
        },
    }

    comparator = ExperimentComparator()
    diff = comparator.compare([exp_a, exp_b])

    assert "comparison_table" in diff
    assert "deltas" in diff
    assert "Clean" in diff["comparison_table"]
    assert "Clean" in diff["deltas"]

    clean_deltas = diff["deltas"]["Clean"]
    # Accuracy: higher is better -> preferred is candidate
    assert pytest.approx(clean_deltas["accuracy"]["absolute_difference"], abs=1e-6) == 0.05
    assert clean_deltas["accuracy"]["preferred"] == "Model Candidate"

    # ECE: lower is better -> preferred is candidate
    assert pytest.approx(clean_deltas["ece"]["absolute_difference"], abs=1e-6) == -0.05
    assert clean_deltas["ece"]["preferred"] == "Model Candidate"

    # Duration: lower is better -> preferred is baseline
    assert pytest.approx(clean_deltas["duration_seconds"]["absolute_difference"], abs=1e-6) == 3.0
    assert clean_deltas["duration_seconds"]["preferred"] == "Model Baseline"


def test_checkpoint_comparison_empty_and_single():
    """Verify ExperimentComparator handles edge cases gracefully."""
    comparator = ExperimentComparator()
    empty_diff = comparator.compare([])
    assert empty_diff["experiment_ids"] == []
    assert empty_diff["deltas"] == {}

    single_exp = {
        "id": "solo",
        "metrics": {"summary": {"accuracy": 0.95}},
    }
    single_diff = comparator.compare([single_exp])
    assert single_diff["experiment_ids"] == ["solo"]
    assert single_diff["deltas"] == {}  # No deltas for 1 experiment
