def test_perfect_error_detection_separation():
    """Verify AUROC=1.0, FPR@95%TPR=0.0, detection_error=0.0 for a perfect detector."""
    # 50 correct samples with entropy 0.1, 50 error samples with entropy 2.0
    n_half = 50
    uncertainties = np.concatenate([np.full(n_half, 0.1), np.full(n_half, 2.0)])
    errors = np.concatenate([np.zeros(n_half, dtype=int), np.ones(n_half, dtype=int)])

    curve = compute_binary_detection_curve(errors, uncertainties)
    assert curve["auroc"] == 1.0
    assert curve["fpr_at_95_tpr"] == 0.0
    assert curve["detection_error"] == 0.0
    assert curve["detection_accuracy"] == 1.0


def test_error_detection_against_sklearn():
    """Verify compute_binary_detection_curve auroc matches scikit-learn roc_auc_score directly."""
    rng = np.random.default_rng(77)
    errors = rng.integers(0, 2, size=100)
    scores = rng.standard_normal(100)

    res = compute_binary_detection_curve(errors, scores)
    expected_auroc = roc_auc_score(errors, scores)
    assert pytest.approx(res["auroc"], abs=1e-6) == expected_auroc


def test_optimal_aurc_theoretical_properties():
    """Verify optimal AURC properties: 0 when no errors, 1 when all errors, and monotonicity."""
    # Zero errors -> 0.0
    assert compute_optimal_aurc(100, 0) == 0.0
    # All errors -> 1.0
    assert compute_optimal_aurc(100, 100) == 1.0
    # Monotonically increasing with error count
    aurc_10 = compute_optimal_aurc(100, 10)
    aurc_30 = compute_optimal_aurc(100, 30)
    aurc_50 = compute_optimal_aurc(100, 50)
    assert 0.0 < aurc_10 < aurc_30 < aurc_50 < 1.0

    # Hand computation: N=4, E=2. n_correct = 2.
    # k in {3, 4}:
    # k=3: (3 - 2)/3 = 1/3
    # k=4: (4 - 2)/4 = 2/4 = 1/2
    # sum = 1/3 + 1/2 = 5/6. Divided by 4: (5/6) / 4 = 5/24 ≈ 0.208333
    expected_hand_aurc = 5.0 / 24.0
    assert pytest.approx(compute_optimal_aurc(4, 2), abs=1e-6) == expected_hand_aurc


def test_selective_prediction_excess_risk():
    """Verify that perfect ranking yields excess_aurc ≈ 0.0 and aurc == optimal_aurc."""
    labels = np.array([0, 0, 0, 1])
    predictions = np.array([0, 0, 0, 0])  # last sample is an error
    confidences = np.array([0.99, 0.95, 0.90, 0.10])  # perfect ranking: error has lowest confidence

    rc = compute_risk_coverage(labels, predictions, confidences)
    assert pytest.approx(rc["excess_aurc"], abs=1e-6) == 0.0
    assert pytest.approx(rc["aurc"], abs=1e-6) == rc["optimal_aurc"]


