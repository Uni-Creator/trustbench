def test_hand_computed_calibration_metrics():
    """Verify ECE and Brier score against manual calculations on a tiny dataset."""
    # 4 samples, 2 classes
    # Sample 0: probs=[0.9, 0.1], label=0 (correct, conf=0.9, acc=1.0)
    # Sample 1: probs=[0.8, 0.2], label=1 (wrong,   conf=0.8, acc=0.0)
    # Sample 2: probs=[0.6, 0.4], label=0 (correct, conf=0.6, acc=1.0)
    # Sample 3: probs=[0.7, 0.3], label=1 (wrong,   conf=0.7, acc=0.0)
    probs = np.array([
        [0.9, 0.1],
        [0.8, 0.2],
        [0.6, 0.4],
        [0.7, 0.3],
    ])
    labels = np.array([0, 1, 0, 1])

    # Brier score: (1/4) * sum_i sum_c (p_ic - y_ic)^2
    # s0: (0.9-1)^2 + (0.1-0)^2 = 0.01 + 0.01 = 0.02
    # s1: (0.8-0)^2 + (0.2-1)^2 = 0.64 + 0.64 = 1.28
    # s2: (0.6-1)^2 + (0.4-0)^2 = 0.16 + 0.16 = 0.32
    # s3: (0.7-0)^2 + (0.3-1)^2 = 0.49 + 0.49 = 0.98
    # Mean = (0.02 + 1.28 + 0.32 + 0.98) / 4 = 2.60 / 4 = 0.65
    expected_brier = 0.65

    metrics = compute_calibration_metrics(labels, probs, n_bins=2)
    assert pytest.approx(metrics["brier_score"], abs=1e-6) == expected_brier

    # Adaptive ECE with 2 bins:
    # Confidences: [0.6, 0.7, 0.8, 0.9], Accuracies: [1.0, 0.0, 0.0, 1.0]
    # Bin 0 (samples 2, 3): confs=[0.6, 0.7] -> mean=0.65, accs=[1.0, 0.0] -> mean=0.5. |0.5 - 0.65| = 0.15
    # Bin 1 (samples 1, 0): confs=[0.8, 0.9] -> mean=0.85, accs=[0.0, 1.0] -> mean=0.5. |0.5 - 0.85| = 0.35
    # AdaECE = 0.5 * 0.15 + 0.5 * 0.35 = 0.25
    ada_ece = compute_adaptive_ece(labels, probs, n_bins=2)
    assert pytest.approx(ada_ece, abs=1e-6) == 0.25


def test_temperature_scaling_converges_for_well_calibrated_logits():
    """Verify that fit_temperature returns ~1.0 when logits are already calibrated."""
    rng = np.random.default_rng(123)
    # Generate data from a logistic regression model (intrinsically calibrated)
    n = 1000
    w = np.array([1.5, -2.0])
    x = rng.standard_normal((n, 2))
    logits_binary = x @ w
    p1 = 1.0 / (1.0 + np.exp(-logits_binary))
    labels = (rng.uniform(size=n) < p1).astype(int)

    # Convert to 2-class logits: [0, logits_binary]
    logits = np.column_stack([np.zeros(n), logits_binary])

    temp = fit_temperature(logits, labels)
    # Since data was generated by the exact softmax/sigmoid, T should be close to 1.0
    assert 0.7 < temp < 1.4, f"Expected temperature near 1.0 for calibrated data, got {temp:.3f}"


def test_temperature_scaling_boundary_behavior():
    """Verify that fit_temperature behaves gracefully when hitting optimization bounds."""
    # Drastically overconfident logits: temperature should hit upper bound (10.0) without crashing
    rng = np.random.default_rng(42)
    n = 200
    logits = rng.standard_normal((n, 5)) * 100.0  # extreme sharpness
    labels = rng.integers(0, 5, size=(n,))

    temp = fit_temperature(logits, labels)
    assert temp <= 10.0
    assert temp > 0.0
    assert not np.isnan(temp)
    assert not np.isinf(temp)

    # Applying this temperature produces valid probabilities
    probs, msp = apply_temperature_scaling(logits, temp)
    assert probs.shape == (n, 5)
    assert np.allclose(np.sum(probs, axis=1), 1.0)
    assert len(msp) == n


def test_held_out_calibration_separation():
    """Verify that calibration fitting on split A improves or evaluates validly on split B."""
    rng = np.random.default_rng(999)
    n_samples = 400
    n_classes = 3
    # Overconfident model
    logits = rng.standard_normal((n_samples, n_classes)) * 2.5
    labels = rng.integers(0, n_classes, size=(n_samples,))

    split = 200
    val_logits, test_logits = logits[:split], logits[split:]
    val_labels, test_labels = labels[:split], labels[split:]

    opt_temp = fit_temperature(val_logits, val_labels)
    assert opt_temp > 1.0, "Expected T > 1.0 for overconfident synthetic logits"

    cal_test_probs, _ = apply_temperature_scaling(test_logits, opt_temp)
    metrics_cal = compute_calibration_metrics(test_labels, cal_test_probs, n_bins=10)
    assert 0.0 <= metrics_cal["ece"] <= 1.0
    assert metrics_cal["brier_score"] >= 0.0


