def _fmt(value: float | None, decimals: int = 4) -> str:
    if value is None:
        return "N/A"
    try:
        return f"{float(value):.{decimals}f}"
    except (TypeError, ValueError):
        return "N/A"


def _badge_cls(value: float | None, threshold_good: float = 0.8) -> str:
    if value is None:
        return ""
    if value >= threshold_good:
        return "good"
    if value >= 0.6:
        return "warn"
    return "bad"


def generate_html_report(
    result: EvaluationResult,
    output_dir: str | Path,
    *,
    config: TrustBenchConfig | None = None,
    experiment_name: str = "unnamed",
) -> Path:
    """Generate a self-contained HTML report from an :class:`EvaluationResult`.

    Args:
        result: Completed evaluation result.
        output_dir: Directory where ``report.html`` will be written.
        config: Optional :class:`TrustBenchConfig` to embed in the report.
        experiment_name: Label shown in the report header.

    Returns:
        Path to the written ``report.html`` file.
    """
    import numpy as np

    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    summary = result.summary or {}
    classification = result.metrics.get("classification", {})

    # -- Summary cards
    summary_cards: list[tuple[str, str]] = [
        ("Accuracy", _fmt(summary.get("accuracy"), 4)),
        ("Macro F1", _fmt(summary.get("macro_f1"), 4)),
        ("ECE", _fmt(summary.get("ece"), 4)),
        ("Brier Score", _fmt(summary.get("brier_score"), 4)),
        ("Mean Entropy", _fmt(summary.get("mean_entropy"), 4)),
        ("Total Samples", str(int(summary.get("total_samples", 0)))),
    ]

    # -- Per-class breakdown
    per_class_rows: list[dict[str, Any]] = []
    per_class_report = classification.get("per_class_report")
    class_names = result.metadata.get("class_names") or []

    if isinstance(per_class_report, dict):
        for cls_key, cls_data in per_class_report.items():
            if not isinstance(cls_data, dict):
                continue
            if cls_key in ("accuracy", "macro avg", "weighted avg"):
                continue
            name = class_names[int(cls_key)] if class_names and cls_key.isdigit() and int(cls_key) < len(class_names) else cls_key
            per_class_rows.append({
                "name": name,
                "precision": _fmt(cls_data.get("precision"), 4),
                "recall": _fmt(cls_data.get("recall"), 4),
                "f1": _fmt(cls_data.get("f1-score"), 4),
                "support": int(cls_data.get("support", 0)),
            })

    # -- Confusion matrix: top off-diagonal entries
    confusion_rows: list[dict[str, Any]] = []
    confusion_matrix = classification.get("confusion_matrix")
    if confusion_matrix is not None:
        try:
            cm = np.asarray(confusion_matrix)
            n_cls = cm.shape[0]
            entries: list[tuple[int, int, int]] = []
            for i in range(n_cls):
                for j in range(n_cls):
                    if i != j and cm[i, j] > 0:
                        entries.append((i, j, int(cm[i, j])))
            entries.sort(key=lambda x: -x[2])
            for true_i, pred_j, count in entries[:10]:
                true_name = class_names[true_i] if class_names and true_i < len(class_names) else str(true_i)
                pred_name = class_names[pred_j] if class_names and pred_j < len(class_names) else str(pred_j)
                confusion_rows.append({
                    "true_cls": true_name,
                    "pred_cls": pred_name,
                    "count": count,
                })
        except (TypeError, ValueError, IndexError):
            pass

    # -- Config JSON
    config_json = None
    if config is not None:
        try:
            config_json = config.model_dump_json(indent=2)
        except (AttributeError, ValueError):
            config_json = None

    # -- Render
    env = Environment(autoescape=select_autoescape(["html"]))
    template = env.from_string(_TEMPLATE_SRC)

    generated_at = datetime.datetime.now(datetime.UTC).strftime(
        "%Y-%m-%d %H:%M:%S UTC"
    )

    html_content = template.render(
        experiment_name=experiment_name,
        generated_at=generated_at,
        summary_cards=summary_cards,
        per_class_rows=per_class_rows,
        confusion_rows=confusion_rows,
        config_json=config_json,
    )

    report_path = out / "report.html"
    report_path.write_text(html_content, encoding="utf-8")
    return report_path
