from jinja2 import Environment, select_autoescape

if TYPE_CHECKING:
    from trustbench.config.schema import TrustBenchConfig
    from trustbench.core.results import EvaluationResult

# ---------------------------------------------------------------------------
# Inline Jinja2 template (self-contained, no CDN)
# ---------------------------------------------------------------------------

